#!/usr/bin/env node
/**
 * Generates `public/qf-shared/*.js` (plugin-system.md §8.3): one ES module per
 * import-map specifier that re-exports the host's own instance of that module
 * from `globalThis.__QUADFLOW_SHARED__` (installed by `src/plugins/shared.ts`
 * before the app renders). Trusted plugins externalize these specifiers, so
 * they share the host's React, hooks, contexts and @quadflow/* singletons.
 *
 * Also writes `public/qf-shared/exports.json` ({ specifier: [names] }) for
 * bundle checks (`@quadflow/plugin-build`, the sandbox runtime), and verifies that the `<script type="importmap">` in
 * index.html maps exactly these specifiers.
 *
 * Usage:
 *   node scripts/gen-shared-shims.mjs   # generate (predev / prebuild:web)
 * Built plugin bundles are checked against exports.json by @quadflow/plugin-build
 * (`quadflow-plugin build` / `quadflow-plugin check-shared <file…>`).
 */
import { createRequire } from 'node:module'
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const outDir = join(root, 'public', 'qf-shared')
const require = createRequire(join(root, 'package.json'))

/**
 * specifier → { file, source }. `cjs`: enumerate `require(spec)`;
 * `ts`: value exports of a TypeScript entry (workspace packages ship TS source).
 */
export const SHARED = [
  { spec: 'react', file: 'react.js', kind: 'cjs' },
  { spec: 'react/jsx-runtime', file: 'react-jsx-runtime.js', kind: 'cjs' },
  { spec: 'react-dom', file: 'react-dom.js', kind: 'cjs' },
  { spec: 'react-dom/client', file: 'react-dom-client.js', kind: 'cjs' },
  { spec: 'zustand', file: 'zustand.js', kind: 'cjs' },
  { spec: '@quadflow/plugin-api', file: 'plugin-api.js', kind: 'ts', entry: 'packages/plugin-api/src/index.ts' },
  { spec: '@quadflow/ui', file: 'ui.js', kind: 'ts', entry: 'packages/ui/src/index.ts' },
]

const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/

function cjsExports(spec) {
  return Object.keys(require(spec)).filter((n) => n !== 'default' && n !== '__esModule' && IDENT.test(n))
}

function tsExports(entry) {
  const ts = require('typescript')
  const file = join(root, entry)
  const program = ts.createProgram([file], {
    target: ts.ScriptTarget.ES2020,
    module: ts.ModuleKind.ESNext,
    moduleResolution: ts.ModuleResolutionKind.Bundler,
    jsx: ts.JsxEmit.ReactJSX,
    allowJs: false,
    skipLibCheck: true,
    noEmit: true,
  })
  const checker = program.getTypeChecker()
  const sf = program.getSourceFile(file)
  if (!sf) throw new Error(`gen-shared-shims: cannot read ${entry}`)
  const modSym = checker.getSymbolAtLocation(sf)
  if (!modSym) return []
  const names = []
  for (const sym of checker.getExportsOfModule(modSym)) {
    const target = sym.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(sym) : sym
    // Value exports only (functions, consts, classes, enums); types vanish at runtime.
    if (target.flags & ts.SymbolFlags.Value && !(target.flags & ts.SymbolFlags.ConstEnum)) {
      const n = sym.getName()
      if (n !== 'default' && IDENT.test(n)) names.push(n)
    }
  }
  return names
}

function shimSource(spec, names) {
  const list = [...names].sort()
  return [
    '// @generated by scripts/gen-shared-shims.mjs. Do not edit.',
    `// Re-exports the QuadFlow host's instance of ${JSON.stringify(spec)} (plugin-system.md §8.3).`,
    `const m = globalThis.__QUADFLOW_SHARED__?.[${JSON.stringify(spec)}];`,
    `if (!m) throw new Error(${JSON.stringify(`QuadFlow shared module "${spec}" is not installed (trusted plugins only)`)});`,
    'export default m.default ?? m;',
    list.length ? `export const { ${list.join(', ')} } = m;` : '',
    '',
  ].join('\n')
}

function checkImportMap() {
  const html = readFileSync(join(root, 'index.html'), 'utf8')
  const m = html.match(/<script type="importmap">([\s\S]*?)<\/script>/)
  if (!m) throw new Error('gen-shared-shims: index.html has no <script type="importmap">')
  const imports = JSON.parse(m[1]).imports ?? {}
  const want = Object.fromEntries(SHARED.map((s) => [s.spec, `/qf-shared/${s.file}`]))
  const a = JSON.stringify(Object.entries(imports).sort())
  const b = JSON.stringify(Object.entries(want).sort())
  if (a !== b) {
    throw new Error(`gen-shared-shims: index.html import map differs from the shim list\n  index.html: ${a}\n  expected:   ${b}`)
  }
  if (html.indexOf('type="importmap"') > html.indexOf('type="module"')) {
    throw new Error('gen-shared-shims: the import map must come before any module script in index.html')
  }
}

function generate() {
  checkImportMap()
  rmSync(outDir, { recursive: true, force: true })
  mkdirSync(outDir, { recursive: true })
  const exportsMap = {}
  for (const s of SHARED) {
    const names = s.kind === 'cjs' ? cjsExports(s.spec) : tsExports(s.entry)
    if (names.length === 0) throw new Error(`gen-shared-shims: ${s.spec} has no exports`)
    exportsMap[s.spec] = [...names].sort()
    writeFileSync(join(outDir, s.file), shimSource(s.spec, names))
  }
  writeFileSync(join(outDir, 'exports.json'), JSON.stringify(exportsMap, null, 2) + '\n')
  console.log(`gen-shared-shims: wrote ${SHARED.length} shims to public/qf-shared/`)
}

const args = process.argv.slice(2)
try {
  if (args.length) throw new Error('gen-shared-shims: no arguments expected (the bundle check is `quadflow-plugin check-shared` from @quadflow/plugin-build)')
  generate()
} catch (e) {
  console.error(e instanceof Error ? e.message : e)
  process.exit(1)
}
