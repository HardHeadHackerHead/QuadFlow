pub fn bindings_path() -> std::path::PathBuf {
    std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../src/generated/bindings.ts")
}

/// Domain types (no commands, no events) for plugin authors (data-layer.md §9).
pub fn plugin_api_types_path() -> std::path::PathBuf {
    std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../packages/plugin-api/src/generated/types.ts")
}

/// Writes `src/generated/bindings.ts` and `packages/plugin-api/src/generated/types.ts`.
pub fn export(builder: &Builder<tauri::Wry>) -> Result<(), String> {
    builder
        .export(specta_typescript::Typescript::default().header(BINDINGS_HEADER), bindings_path())
        .map_err(|e| format!("export bindings: {e}"))?;
    export_plugin_api_types(builder)
}

/// Every type the commands/events reference, exported without the command and
/// event runtime (so the file has no `@tauri-apps/api` import).
pub fn export_plugin_api_types(builder: &Builder<tauri::Wry>) -> Result<(), String> {
    struct Types<'a>(&'a mut Option<specta::Types>);
    impl LanguageExt for Types<'_> {
        type Error = std::io::Error;
        fn export(self, cfg: &BuilderConfiguration, _path: &std::path::Path) -> Result<(), Self::Error> {
            *self.0 = Some(cfg.types.clone());
            Ok(())
        }
    }
    let mut types = None;
    let _ = builder.export(Types(&mut types), "");
    let types = types.ok_or_else(|| "export plugin-api types: no type collection".to_string())?;
    Builder::<tauri::Wry>::new()
        .types(&types)
        .dangerously_cast_bigints_to_number()
        .export(specta_typescript::Typescript::default().header(BINDINGS_HEADER), plugin_api_types_path())
        .map_err(|e| format!("export plugin-api types: {e}"))
}

/// Names of the commands registered with tauri-specta, so the shell can route
/// an invoke to the typed handler or to the untyped `generate_handler!` one.
pub fn command_names(builder: &Builder<tauri::Wry>) -> HashSet<String> {
    struct Names<'a>(&'a mut HashSet<String>);
    impl LanguageExt for Names<'_> {
        type Error = std::io::Error;
        fn export(self, cfg: &BuilderConfiguration, _path: &std::path::Path) -> Result<(), Self::Error> {
            self.0.extend(cfg.commands.iter().map(|f| f.name().to_string()));
            Ok(())
        }
    }
    let mut set = HashSet::new();
    let _ = builder.export(Names(&mut set), "");
    set
}
