/// Initialize on app boot: writes metadata snapshots, records a
/// "startup" breadcrumb, ensures the log directory exists, and prunes
/// stale crash reports / bundles so the directory doesn't grow without
/// bound on long-running installs.
pub fn init() {
    if let Some(d) = dir() {
        let _ = std::fs::create_dir_all(&d);
    }
    cleanup_old_files();
    let _ = write_metadata_files();
    record(
        "info",
        "lifecycle",
        format!(
            "QuadFlow {} (git {}) startup",
            env!("CARGO_PKG_VERSION"),
            option_env!("QUADFLOW_GIT_SHA").unwrap_or("?"),
        ),
    );
}

/// Convenience for use FROM the SEH and panic hooks: assemble a
/// CrashReport with a given kind/message/location and the rest filled
/// in from snapshot-able state. Does NOT write — caller does that so
/// they can attach raw frames first.
pub fn build_report(
    kind: CrashKind,
    message: impl Into<String>,
    location: Option<String>,
) -> CrashReport {
    CrashReport {
        schema_version: 1,
        timestamp: Utc::now().to_rfc3339(),
        kind,
        message: message.into(),
        location,
        raw_frames: vec![],
        symbolized_backtrace: None,
        js_stack: None,
        thread: format!("{:?}", std::thread::current().id()),
        pid: std::process::id(),
        breadcrumbs: snapshot_breadcrumbs(),
        build_info: build_info(),
        system_info: system_info(),
    }
}

