//! Crash + diagnostics infrastructure.
//!
//! Goals:
//! - Every log line is captured into an in-memory ring buffer (last 500
//!   records) so a crash report carries the full lead-up no matter where
//!   in the codebase the crash originated.
//! - Crash reports (Rust panics, Windows SEH faults, frontend JS errors)
//!   all produce the SAME JSON shape, so a single bug-report flow handles
//!   every category. Each report carries its own breadcrumbs snapshot,
//!   build info, and system info — the file is self-contained.
//! - One Tauri command (`generate_diagnostic_bundle`) zips logs +
//!   crashes + metadata into a single attachable archive. Privacy-aware:
//!   redacts `%USERNAME%` from paths and any env var matching
//!   *KEY*/*TOKEN*/*SECRET*/*PASSWORD*.
//!
//! Layout written to the profile-aware core logs dir (`AppPaths::logs_dir`):
//! - `quadflow.log[.N]` — rotating freeform log (tauri-plugin-log)
//! - `breadcrumbs.jsonl` — running JSON-line breadcrumbs (debug aid)
//! - `crash-<ts>-<kind>-pid<P>-<thread>.json` — one file per crash event
//! - `system-info.json` — captured once at boot, refreshed on bundle
//! - `build-info.json` — compile-time metadata
//! - `bundle-<ts>.zip` — generated by `generate_diagnostic_bundle`

use std::collections::VecDeque;
use std::path::PathBuf;
use std::sync::OnceLock;

use chrono::{DateTime, Utc};
use parking_lot::Mutex;
use serde::{Deserialize, Serialize};

const BREADCRUMB_CAPACITY: usize = 500;

/// Per-section caps on a single crash report so a runaway breadcrumb
/// flood or a thousand-frame stack walk can't produce unmanageable
/// JSON files. Numbers chosen to fit a typical bug report comfortably:
/// 500 breadcrumbs ≈ ~150 KB, 256 frames covers any realistic
/// recursion, 64 KB symbolized backtrace is plenty for ~200 frames.
const MAX_RAW_FRAMES_KEPT: usize = 256;
const MAX_SYMBOLIZED_BACKTRACE_BYTES: usize = 64 * 1024;
const MAX_BREADCRUMBS_KEPT_IN_REPORT: usize = BREADCRUMB_CAPACITY;
const MAX_JS_STACK_BYTES: usize = 16 * 1024;

/// Disk quota: how many `crash-*.json` files we keep on disk before the
/// oldest are deleted on next boot. Long-running installs without this
/// would accumulate forever.
const MAX_CRASH_REPORTS_RETAINED: usize = 50;
const MAX_BUNDLES_RETAINED: usize = 5;

/// One captured event in chronological order. Levels mirror `log::Level`
/// plus a "user" category for explicit user-action breadcrumbs from the
/// frontend (e.g. "clicked Patch button").
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Breadcrumb {
    /// RFC3339 UTC timestamp.
    pub ts: String,
    pub level: String,
    /// Module path (Rust target) or component name (frontend).
    pub category: String,
    pub message: String,
    /// Optional structured fields. Frontend uses this for click context;
    /// Rust uses it for ad-hoc key=val payloads.
    #[serde(default, skip_serializing_if = "serde_json::Map::is_empty")]
    pub fields: serde_json::Map<String, serde_json::Value>,
}

static BREADCRUMBS: OnceLock<Mutex<VecDeque<Breadcrumb>>> = OnceLock::new();

fn breadcrumbs() -> &'static Mutex<VecDeque<Breadcrumb>> {
    BREADCRUMBS.get_or_init(|| Mutex::new(VecDeque::with_capacity(BREADCRUMB_CAPACITY)))
}

/// Push a breadcrumb. Lock-free at peak load: parking_lot mutex on a
/// VecDeque is essentially free. Also tees to the freeform log so that
/// breadcrumbs are visible in `quadflow.log` for live tailing.
pub fn record(level: &str, category: &str, message: impl Into<String>) {
    record_with_fields(level, category, message, serde_json::Map::new())
}

pub fn record_with_fields(
    level: &str,
    category: &str,
    message: impl Into<String>,
    fields: serde_json::Map<String, serde_json::Value>,
) {
    let bc = Breadcrumb {
        ts: Utc::now().to_rfc3339(),
        level: level.to_string(),
        category: category.to_string(),
        message: message.into(),
        fields,
    };
    let mut buf = breadcrumbs().lock();
    if buf.len() >= BREADCRUMB_CAPACITY {
        buf.pop_front();
    }
    buf.push_back(bc.clone());
    drop(buf);

    // Tee to the freeform log so live-tailing `quadflow.log` shows
    // breadcrumbs alongside everything else. Level mapping is loose —
    // anything we don't recognise lands at INFO.
    match level {
        "error" => log::error!(target: "breadcrumb", "[{category}] {}", bc.message),
        "warn" => log::warn!(target: "breadcrumb", "[{category}] {}", bc.message),
        "debug" | "trace" => log::debug!(target: "breadcrumb", "[{category}] {}", bc.message),
        _ => log::info!(target: "breadcrumb", "[{category}] {}", bc.message),
    }
}

/// Snapshot the current breadcrumb ring into a fresh Vec. Cheap clone —
/// we hold the mutex for microseconds.
pub fn snapshot_breadcrumbs() -> Vec<Breadcrumb> {
    breadcrumbs().lock().iter().cloned().collect()
}

