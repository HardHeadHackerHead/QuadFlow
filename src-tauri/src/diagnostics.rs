#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct BuildInfo {
    pub version: String,
    pub git_sha: String,
    pub git_dirty: bool,
    pub build_timestamp: String,
    pub profile: String,
    pub target: String,
    pub rustc_version: String,
}

pub fn build_info() -> BuildInfo {
    BuildInfo {
        version: env!("CARGO_PKG_VERSION").to_string(),
        git_sha: option_env!("QUADFLOW_GIT_SHA").unwrap_or("unknown").to_string(),
        git_dirty: option_env!("QUADFLOW_GIT_DIRTY")
            .map(|v| v == "true")
            .unwrap_or(false),
        build_timestamp: option_env!("QUADFLOW_BUILD_TIMESTAMP").unwrap_or("unknown").to_string(),
        profile: option_env!("QUADFLOW_BUILD_PROFILE").unwrap_or("unknown").to_string(),
        target: option_env!("QUADFLOW_BUILD_TARGET").unwrap_or("unknown").to_string(),
        // Bare metal — no rustc -V at runtime; we record the version that
        // built us.
        rustc_version: option_env!("CARGO_PKG_RUST_VERSION")
            .unwrap_or("unknown")
            .to_string(),
    }
}

