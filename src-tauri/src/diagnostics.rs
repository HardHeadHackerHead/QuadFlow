/// Create a single zip archive containing every diagnostic artifact
/// (logs, crash reports, system+build info). Returns the path. Caller
/// is responsible for revealing the file — typical UI flow opens
/// File Explorer to its folder.
pub fn generate_bundle(active_project: Option<PathBuf>) -> std::io::Result<PathBuf> {
    use std::io::Write;
    use zip::write::SimpleFileOptions;
    use zip::CompressionMethod;

    // Refresh metadata so the bundle reflects current state, not boot
    // state. Cheap operation.
    let _ = write_metadata_files();

    let dir = dir().ok_or_else(|| std::io::Error::new(std::io::ErrorKind::NotFound, "no log dir"))?;
    std::fs::create_dir_all(&dir)?;

    // Snapshot breadcrumbs to a file inside the bundle. We do this even
    // though no crash has fired — the bundle should always include
    // recent activity.
    let breadcrumbs = snapshot_breadcrumbs();
    let bc_path = dir.join("breadcrumbs.json");
    std::fs::write(
        &bc_path,
        serde_json::to_string_pretty(&breadcrumbs).unwrap_or_default(),
    )?;

    let ts = Utc::now().format("%Y%m%dT%H%M%S");
    let bundle_path = dir.join(format!("bundle-{ts}.zip"));
    let zip_file = std::fs::File::create(&bundle_path)?;
    let mut zip = zip::ZipWriter::new(zip_file);
    let opts: SimpleFileOptions = SimpleFileOptions::default().compression_method(CompressionMethod::Deflated);

    // Walk the log directory and add everything except other bundles.
    for entry in std::fs::read_dir(&dir)?.flatten() {
        let p = entry.path();
        if p.extension().and_then(|s| s.to_str()) == Some("zip") {
            continue;
        }
        if !p.is_file() {
            continue;
        }
        let name = match p.file_name().and_then(|s| s.to_str()) {
            Some(n) => n.to_string(),
            None => continue,
        };
        zip.start_file(&name, opts)?;
        let bytes = std::fs::read(&p)?;
        zip.write_all(&bytes)?;
    }

    // Per-project context: include the active project's ship config and its
    // agent context files (root `*.md` with a QuadFlow managed region) under a
    // `project/` prefix in the zip. These are the smoking gun for ~70% of
    // Ship-related bug reports.
    if let Some(project_path) = active_project {
        let candidates: &[(&str, &str)] = &[
            (if quadflow_core::Profile::current() == quadflow_core::Profile::Dev { ".quadflow-dev/ship/config.json" } else { ".quadflow/ship/config.json" }, "project/ship-config.json"),
            ("package.json", "project/package.json"),
        ];
        let context_files: Vec<(String, String)> = std::fs::read_dir(&project_path)
            .map(|rd| {
                rd.filter_map(|e| e.ok())
                    .map(|e| e.path())
                    .filter(|p| p.extension().is_some_and(|x| x == "md") && p.is_file())
                    .filter(|p| std::fs::read_to_string(p).is_ok_and(|s| s.contains("<!-- quadflow:context:start")))
                    .filter_map(|p| p.file_name().map(|n| n.to_string_lossy().to_string()))
                    .map(|n| (n.clone(), format!("project/{n}")))
                    .collect()
            })
            .unwrap_or_default();
        for (rel, dest) in &context_files {
            if let Ok(bytes) = std::fs::read(project_path.join(rel)) {
                if zip.start_file(dest.as_str(), opts).is_ok() {
                    let _ = zip.write_all(&bytes);
                }
            }
        }
        for (rel, dest) in candidates {
            let src = project_path.join(rel);
            if src.is_file() {
                if let Ok(bytes) = std::fs::read(&src) {
                    if zip.start_file(*dest, opts).is_ok() {
                        let _ = zip.write_all(&bytes);
                    }
                }
            }
        }
        // Also include the active project path itself as text so we can
        // see what was loaded at bundle time.
        let _ = zip.start_file("project/active-project.txt", opts);
        let _ = zip.write_all(redact_user_home(&project_path.display().to_string(), &dirs::home_dir()
            .map(|p| p.display().to_string())
            .unwrap_or_default()).as_bytes());
    }

    zip.finish()?;
    Ok(bundle_path)
}

