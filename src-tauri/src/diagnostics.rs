#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SystemInfo {
    pub captured_at: String,
    pub os: String,
    pub os_version: String,
    pub arch: String,
    pub num_cpus: usize,
    pub locale: String,
    pub timezone_offset_secs: i32,
    pub exe_path: String,
    pub appdata_dir: String,
    pub cwd: String,
    pub user_home_redacted: String,
    /// Subset of env vars; secrets-shaped names are pre-redacted.
    pub env_excerpt: serde_json::Map<String, serde_json::Value>,
}

pub fn system_info() -> SystemInfo {
    let exe_path = std::env::current_exe()
        .map(|p| p.display().to_string())
        .unwrap_or_else(|_| "unknown".into());
    let cwd = std::env::current_dir()
        .map(|p| p.display().to_string())
        .unwrap_or_else(|_| "unknown".into());
    let appdata_dir = quadflow_core::AppPaths::resolve().ok().map(|p| p.data_dir)
        .map(|p| p.display().to_string())
        .unwrap_or_else(|| "unknown".into());

    let user_home = dirs::home_dir()
        .map(|p| p.display().to_string())
        .unwrap_or_default();

    SystemInfo {
        captured_at: Utc::now().to_rfc3339(),
        os: std::env::consts::OS.to_string(),
        os_version: os_version(),
        arch: std::env::consts::ARCH.to_string(),
        num_cpus: std::thread::available_parallelism()
            .map(|n| n.get())
            .unwrap_or(1),
        locale: std::env::var("LANG")
            .or_else(|_| std::env::var("LC_ALL"))
            .or_else(|_| std::env::var("LANGUAGE"))
            .unwrap_or_else(|_| "unknown".into()),
        timezone_offset_secs: chrono::Local::now().offset().local_minus_utc(),
        exe_path: redact_user_home(&exe_path, &user_home),
        appdata_dir: redact_user_home(&appdata_dir, &user_home),
        cwd: redact_user_home(&cwd, &user_home),
        user_home_redacted: "<HOME>".into(),
        env_excerpt: env_excerpt(),
    }
}

#[cfg(target_os = "windows")]
fn os_version() -> String {
    // RtlGetVersion is the lying-proof way to get the actual Windows
    // version (GetVersionEx returns 6.2 for Win10+ unless manifested).
    // Bare FFI to avoid pulling in the windows crate's version surface.
    extern "system" {
        fn RtlGetVersion(info: *mut OsVersionInfo) -> i32;
    }
    #[repr(C)]
    struct OsVersionInfo {
        os_version_info_size: u32,
        major: u32,
        minor: u32,
        build_number: u32,
        platform_id: u32,
        csd_version: [u16; 128],
        service_pack_major: u16,
        service_pack_minor: u16,
        suite_mask: u16,
        product_type: u8,
        reserved: u8,
    }
    // Zero-init; manual sized initialiser since [u16; 128] doesn't impl Default.
    let mut info: OsVersionInfo = unsafe { std::mem::zeroed() };
    info.os_version_info_size = std::mem::size_of::<OsVersionInfo>() as u32;
    let status = unsafe { RtlGetVersion(&mut info as *mut _) };
    if status == 0 {
        format!(
            "Windows {}.{}.{} (build {})",
            info.major, info.minor, info.build_number, info.build_number
        )
    } else {
        "Windows (unknown version)".into()
    }
}

#[cfg(not(target_os = "windows"))]
fn os_version() -> String {
    std::process::Command::new("uname")
        .arg("-srm")
        .output()
        .ok()
        .and_then(|o| String::from_utf8(o.stdout).ok())
        .map(|s| s.trim().to_string())
        .unwrap_or_else(|| "unknown".into())
}

/// Filtered subset of env vars. Drops anything matching a secret-shaped
/// name (case-insensitive substring match on KEY/TOKEN/SECRET/PASSWORD/AUTH).
fn env_excerpt() -> serde_json::Map<String, serde_json::Value> {
    let mut out = serde_json::Map::new();
    let interesting = [
        "PATH",
        "RUST_BACKTRACE",
        "RUST_LOG",
        "QUADFLOW_PROJECT_DIR",
        "TZ",
        "TEMP",
        "TMP",
        "PROCESSOR_ARCHITECTURE",
        "PROCESSOR_IDENTIFIER",
        "NUMBER_OF_PROCESSORS",
        "OS",
        "USERPROFILE",
    ];
    let user_home = dirs::home_dir().map(|p| p.display().to_string()).unwrap_or_default();
    for k in interesting {
        if let Ok(v) = std::env::var(k) {
            // Don't include obvious secrets even from the allow-list.
            if looks_like_secret_name(k) {
                out.insert(k.to_string(), serde_json::Value::String("<REDACTED>".into()));
            } else {
                out.insert(
                    k.to_string(),
                    serde_json::Value::String(redact_user_home(&v, &user_home)),
                );
            }
        }
    }
    out
}

fn looks_like_secret_name(name: &str) -> bool {
    let upper = name.to_uppercase();
    [
        "KEY", "TOKEN", "SECRET", "PASSWORD", "PWD", "AUTH", "CREDENTIAL",
    ]
    .iter()
    .any(|needle| upper.contains(needle))
}

fn redact_user_home(path: &str, home: &str) -> String {
    if home.is_empty() {
        return path.to_string();
    }
    path.replace(home, "<HOME>")
}

