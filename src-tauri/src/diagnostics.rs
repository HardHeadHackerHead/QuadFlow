#[derive(Debug, Clone, Deserialize)]
pub struct FrontendErrorReport {
    pub kind: String, // "error" | "promise" | "console_error"
    pub message: String,
    pub source: Option<String>,
    pub line: Option<u32>,
    pub column: Option<u32>,
    pub stack: Option<String>,
    pub url: Option<String>,
}

/// Persist a frontend error as a CrashReport (and also as a breadcrumb).
pub fn record_frontend_error(payload: FrontendErrorReport) -> Option<PathBuf> {
    let kind = match payload.kind.as_str() {
        "promise" => CrashKind::FrontendPromiseRejection,
        _ => CrashKind::FrontendError,
    };
    record_with_fields(
        "error",
        "frontend",
        format!("[{}] {}", payload.kind, payload.message),
        {
            let mut m = serde_json::Map::new();
            if let Some(s) = &payload.source { m.insert("source".into(), s.clone().into()); }
            if let Some(l) = payload.line { m.insert("line".into(), l.into()); }
            if let Some(c) = payload.column { m.insert("column".into(), c.into()); }
            if let Some(u) = &payload.url { m.insert("url".into(), u.clone().into()); }
            m
        },
    );

    let location = match (payload.source.as_ref(), payload.line) {
        (Some(s), Some(l)) => Some(format!("{s}:{l}")),
        (Some(s), None) => Some(s.clone()),
        _ => None,
    };

    let report = CrashReport {
        schema_version: 1,
        timestamp: Utc::now().to_rfc3339(),
        kind,
        message: payload.message.clone(),
        location,
        raw_frames: vec![],
        symbolized_backtrace: None,
        js_stack: payload.stack.clone(),
        thread: format!("{:?}", std::thread::current().id()),
        pid: std::process::id(),
        breadcrumbs: snapshot_breadcrumbs(),
        build_info: build_info(),
        system_info: system_info(),
    };
    write_crash_report(&report).ok()
}

