/// What kind of crash this report represents. Used as a filename suffix
/// and to drive any downstream triage.
#[derive(Debug, Clone, Copy, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum CrashKind {
    /// `panic!` from any Rust thread.
    RustPanic,
    /// Windows hardware exception (stack overflow, access violation, …).
    SehFault,
    /// `window.onerror` from the WebView.
    FrontendError,
    /// `unhandledrejection` from the WebView.
    FrontendPromiseRejection,
}

impl CrashKind {
    pub fn slug(&self) -> &'static str {
        match self {
            CrashKind::RustPanic => "panic",
            CrashKind::SehFault => "seh",
            CrashKind::FrontendError => "frontend",
            CrashKind::FrontendPromiseRejection => "promise",
        }
    }
}

/// JSON crash report — the canonical shape every crash source produces.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CrashReport {
    pub schema_version: u32,
    pub timestamp: String,
    pub kind: CrashKind,
    /// Human-readable summary (e.g. panic message, exception label, JS
    /// error.message).
    pub message: String,
    /// Optional source location string.
    pub location: Option<String>,
    /// Stack frames as raw addresses + RVAs (always populated for SEH;
    /// optional for others where a backtrace is available).
    pub raw_frames: Vec<RawFrame>,
    /// Best-effort dbghelp/backtrace-resolved frames as a single string.
    /// Empty for frontend errors (use `js_stack` instead).
    pub symbolized_backtrace: Option<String>,
    /// JS-side stack trace, as a string. Only populated for frontend
    /// kinds.
    pub js_stack: Option<String>,
    pub thread: String,
    pub pid: u32,
    pub breadcrumbs: Vec<Breadcrumb>,
    pub build_info: BuildInfo,
    pub system_info: SystemInfo,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RawFrame {
    pub index: u32,
    pub address: String, // hex-formatted absolute pointer
    pub rva: String,     // hex-formatted offset within the exe
}

/// Where on disk to write all of our diagnostics output.
pub fn dir() -> Option<PathBuf> {
    quadflow_core::AppPaths::resolve().ok().map(|p| p.logs_dir)
}

/// Apply per-section size caps to a crash report so disk + bundle stay
/// reasonable even for pathological crashes (deep recursion, breadcrumb
/// flood, gigantic JS stack). Mutates in place.
fn apply_report_caps(report: &mut CrashReport) {
    if report.raw_frames.len() > MAX_RAW_FRAMES_KEPT {
        report.raw_frames.truncate(MAX_RAW_FRAMES_KEPT);
    }
    if report.breadcrumbs.len() > MAX_BREADCRUMBS_KEPT_IN_REPORT {
        // Keep MOST RECENT events — the ones immediately before the crash.
        let drop = report.breadcrumbs.len() - MAX_BREADCRUMBS_KEPT_IN_REPORT;
        report.breadcrumbs.drain(0..drop);
    }
    if let Some(bt) = &mut report.symbolized_backtrace {
        if bt.len() > MAX_SYMBOLIZED_BACKTRACE_BYTES {
            bt.truncate(MAX_SYMBOLIZED_BACKTRACE_BYTES);
            bt.push_str("\n[truncated by diagnostics::apply_report_caps]");
        }
    }
    if let Some(js) = &mut report.js_stack {
        if js.len() > MAX_JS_STACK_BYTES {
            js.truncate(MAX_JS_STACK_BYTES);
            js.push_str("\n[truncated by diagnostics::apply_report_caps]");
        }
    }
}

/// Write a structured crash report to disk. Filename is unique per (ts,
/// pid, thread) so concurrent crashes can't trample each other. Always
/// fsync'd via flush before return so a process termination immediately
/// after this call still leaves a record on disk. Applies per-section
/// caps so a single crash file can't grow unbounded.
pub fn write_crash_report(report: &CrashReport) -> std::io::Result<PathBuf> {
    use std::io::Write;
    let mut report = report.clone();
    apply_report_caps(&mut report);

    let dir = dir().ok_or_else(|| std::io::Error::new(std::io::ErrorKind::NotFound, "no log dir"))?;
    std::fs::create_dir_all(&dir)?;
    let ts_compact = Utc::now().format("%Y%m%dT%H%M%S");
    let file_name = format!(
        "crash-{ts_compact}-{kind}-pid{pid}-tid{tid}.json",
        kind = report.kind.slug(),
        pid = report.pid,
        tid = sanitize_for_filename(&report.thread),
    );
    let path = dir.join(file_name);
    let mut f = std::fs::OpenOptions::new()
        .create(true)
        .append(true)
        .open(&path)?;
    let json = serde_json::to_string_pretty(&report)
        .unwrap_or_else(|e| format!("{{\"serialize_error\":\"{e}\"}}"));
    f.write_all(json.as_bytes())?;
    f.write_all(b"\n")?;
    f.flush()?;
    #[cfg(target_os = "windows")]
    unsafe {
        use std::os::windows::io::AsRawHandle;
        extern "system" {
            fn FlushFileBuffers(handle: *mut std::ffi::c_void) -> i32;
        }
        let _ = FlushFileBuffers(f.as_raw_handle() as *mut _);
    }
    Ok(path)
}

/// Sweep the diagnostics directory at startup. Deletes the oldest
/// `crash-*.json` files past `MAX_CRASH_REPORTS_RETAINED` and the
/// oldest `bundle-*.zip` past `MAX_BUNDLES_RETAINED`. Best-effort —
/// failures are logged but never abort startup.
pub fn cleanup_old_files() {
    let dir = match self::dir() {
        Some(d) => d,
        None => return,
    };
    let prune = |prefix: &str, suffix: &str, max: usize| {
        let Ok(read) = std::fs::read_dir(&dir) else { return };
        let mut matching: Vec<(std::time::SystemTime, PathBuf)> = read
            .flatten()
            .filter_map(|e| {
                let p = e.path();
                let name = p.file_name()?.to_str()?.to_string();
                if !name.starts_with(prefix) || !name.ends_with(suffix) {
                    return None;
                }
                let mtime = e.metadata().ok().and_then(|m| m.modified().ok())?;
                Some((mtime, p))
            })
            .collect();
        if matching.len() <= max {
            return;
        }
        // Sort newest first so we keep the head and delete the tail.
        matching.sort_by(|a, b| b.0.cmp(&a.0));
        for (_, p) in matching.into_iter().skip(max) {
            let _ = std::fs::remove_file(&p);
        }
    };
    prune("crash-", ".json", MAX_CRASH_REPORTS_RETAINED);
    prune("bundle-", ".zip", MAX_BUNDLES_RETAINED);
}

fn sanitize_for_filename(s: &str) -> String {
    s.chars()
        .map(|c| match c {
            'a'..='z' | 'A'..='Z' | '0'..='9' | '-' | '_' => c,
            _ => '_',
        })
        .collect()
}

/// Refresh the on-disk `system-info.json` and `build-info.json` snapshots.
/// Called once at boot so a frozen process can still report its config.
pub fn write_metadata_files() -> std::io::Result<()> {
    let dir = dir().ok_or_else(|| std::io::Error::new(std::io::ErrorKind::NotFound, "no log dir"))?;
    std::fs::create_dir_all(&dir)?;
    let bi = build_info();
    let si = system_info();
    std::fs::write(
        dir.join("build-info.json"),
        serde_json::to_string_pretty(&bi).unwrap_or_default(),
    )?;
    std::fs::write(
        dir.join("system-info.json"),
        serde_json::to_string_pretty(&si).unwrap_or_default(),
    )?;
    Ok(())
}

